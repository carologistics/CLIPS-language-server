/** Deffunctions named like a host function and a built-in. */
const clashSrc = `(deffunction clash-me () 1)
(deffunction abs (?x) ?x)
`;

/** An unfinished call, for completion. */
const compSrc = `(defrule c => (dis`;
const compTemplateSrc = `(defrule c2 (gr`;
const compClassSrc = `(defrule c3 (object (is-a A`;

const heldSrc = `(defrule held
   (gripper (open ?o))
   (object (is-a Arm))
   =>
   (printout t ?*sim-time* crlf))
`;

/** A file outside the dump's folder, where the declarations don't apply. */
const outsideSrc = `(defrule far
   (sensor (id ?id))
   =>
   (printout t (distance 1 2 3 4) crlf))
`;

/** Temporary workspace folder. */
const dir = mkdtempSync(join(tmpdir(), 'clips-decl-'));
mkdirSync(join(dir, 'host'));
mkdirSync(join(dir, 'other'));
/** Fixture paths by key. */
const paths = {
  host: join(dir, 'host', 'host.clpd'),
  extra: join(dir, 'host', 'extra.clpd'),
  main: join(dir, 'host', 'main.clp'),
  rules: join(dir, 'host', 'rules.clp'),
  clash: join(dir, 'host', 'clash.clp'),
  comp: join(dir, 'host', 'comp.clp'),
  compTemplate: join(dir, 'host', 'comp2.clp'),
  compClass: join(dir, 'host', 'comp3.clp'),
  held: join(dir, 'host', 'held.clp'),
  outside: join(dir, 'other', 'outside.clp')
};
/** Fixture texts by key. */
const sources = { host: hostSrc, extra: extraSrc, main: mainSrc, rules: rulesSrc, clash: clashSrc, comp: compSrc, outside: outsideSrc, compTemplate: compTemplateSrc, compClass: compClassSrc, held: heldSrc };
for (const [key, path] of Object.entries(paths)) writeFileSync(path, sources[key]);
/** Fixture URIs by key. */
const uri = Object.fromEntries(Object.entries(paths).map(([key, path]) => [key, pathToFileURL(path).href]));
/** URI of the workspace folder. */
const folderUri = pathToFileURL(dir).href;

/**
 * The position of the `occurrence`-th `needle` in `src`.
 *
 * @param src - The text.
 * @param needle - Text to find.
 * @param occurrence - Which match, 0-based.
 * @returns The LSP position.
 */
function position(src, needle, occurrence = 0) {
  let index = -1;
  for (let i = 0; i <= occurrence; i++) {
    index = src.indexOf(needle, index + 1);
    if (index === -1) throw new Error(`needle not found: "${needle}"`);
  }
  const before = src.slice(0, index);
  return { line: (before.match(/\n/g) ?? []).length, character: index - before.lastIndexOf('\n') - 1 };
}

/**
 * Resolves after `ms` milliseconds.
 *
 * @param ms - The delay.
 * @returns The promise.
 */
const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));
/** Long enough for indexing plus the server's revalidation debounce. */
const SETTLE_MS = 800;

/** The server under test. */
const child = spawn(process.execPath, [serverPath, '--stdio'], { stdio: ['pipe', 'pipe', 'pipe'] });
child.stderr.on('data', (chunk) => process.stderr.write(`[server stderr] ${chunk}`));
/** JSON-RPC connection to the server. */
const connection = createMessageConnection(new StreamMessageReader(child.stdout), new StreamMessageWriter(child.stdin));

/** Latest diagnostics by lowercased path. */
const latest = new Map();
connection.onNotification('textDocument/publishDiagnostics', (p) => latest.set(fileURLToPath(p.uri).toLowerCase(), p.diagnostics));
connection.onRequest('workspace/configuration', (p) => p.items.map(() => ({})));
connection.onRequest('client/registerCapability', () => null);
connection.listen();

/**
 * Latest diagnostics of a fixture.
 *
 * @param key - The fixture key.
 * @returns The diagnostics.
 */
const diagnosticsOf = (key) => latest.get(paths[key].toLowerCase()) ?? [];
/**
 * Diagnostic messages of a fixture.
 *
 * @param key - The fixture key.
 * @returns The messages.
 */
const messages = (key) => diagnosticsOf(key).map((d) => d.message);
/**
 * Whether a message of the fixture contains `text`.
 *
 * @param key - The fixture key.
 * @param text - The text.
 */
const has = (key, text) => messages(key).some((m) => m.includes(text));
/**
 * Diagnostics of a fixture with the given code.
 *
 * @param key - The fixture key.
 * @param code - The code without `clips(...)`.
 * @returns The diagnostics.
 */
const withCode = (key, code) => diagnosticsOf(key).filter((d) => d.code === `clips(${code})`);

/** Number of failed checks. */
let failures = 0;
/**
 * Records a check result.
 *
 * @param label - What is checked.
 * @param pass - Whether it passed.
 * @param detail - Printed on failure.
 */
function check(label, pass, detail = '') {
  console.log(`${pass ? 'PASS' : 'FAIL'}  ${label}${!pass && detail ? `  (${detail})` : ''}`);
  if (!pass) failures++;
}

try {
  await connection.sendRequest('initialize', {
    processId: process.pid,
    rootUri: folderUri,
    workspaceFolders: [{ uri: folderUri, name: 'ws' }],
    capabilities: { workspace: { workspaceFolders: true, configuration: true }, textDocument: { completion: { completionItem: { snippetSupport: true } } } }
  });
  await connection.sendNotification('initialized', {});
  await sleep(SETTLE_MS);
  for (const key of ['rules', 'clash', 'outside', 'host', 'extra', 'comp', 'compTemplate', 'compClass', 'held']) {
    connection.sendNotification('textDocument/didOpen', { textDocument: { uri: uri[key], languageId: 'clips', version: 1, text: sources[key] } });
  }
  await sleep(SETTLE_MS);
  const rules = JSON.stringify(messages('rules'));

  // 1. Names from the dump resolve.
  check('host function is known', !has('rules', 'Unknown function "distance"'), rules);
  check('deffunction from the dump is known', !has('rules', 'Unknown function "celsius-to-f"'), rules);
  check('name-only host function from a hand-written file is known', !has('rules', 'Unknown function "plan-path"'), rules);
  check('template from the dump is known', !has('rules', 'Unknown deftemplate'), rules);
  check('global from the dump is known', !has('rules', 'Unknown global'), rules);
  check('class from the dump is known', !has('rules', 'Unknown class'), rules);
  check('nothing from the dump is "not loaded" in a known program', !has('rules', 'no (load …)'), rules);
  check('an undeclared function is still unknown', has('rules', 'Unknown function "new-fn"'), rules);

  // 2. Host-function arity.
  const arity = withCode('rules', 'function-arity');
  check('wrong host-function arity is an error', arity.length === 1 && arity[0].message.includes('"distance" expects exactly 4 arguments, but this call has 2'), JSON.stringify(arity));
  check('arity error points at the defudf line', arity[0]?.relatedInformation?.[0]?.location.uri.toLowerCase().endsWith('host.clpd'), JSON.stringify(arity[0]?.relatedInformation));

  // 3. The dump applies to its own folder only.
  check('outside the folder the host function is unknown', has('outside', 'Unknown function "distance"'), JSON.stringify(messages('outside')));
  check('outside the folder the dumped template is unknown', has('outside', 'Unknown deftemplate "sensor"'), JSON.stringify(messages('outside')));

  // 4. A deffunction may not replace an external function.
  const clash = withCode('clash', 'deffunction-replaces-external');
  check('deffunction named like a host function', clash.some((d) => d.message.startsWith('"clash-me" is a function the host program registers')), JSON.stringify(clash));
  check('deffunction named like a built-in', clash.some((d) => d.message.startsWith('"abs" is a CLIPS built-in')), JSON.stringify(clash));

  // 5. The declaration files' own checks.
  const host = JSON.stringify(diagnosticsOf('host').map((d) => d.code));
  check('construct also in a .clp file: late dump', withCode('host', 'declaration-late-dump').some((d) => d.message.includes('"dup" is also defined in rules.clp')), host);
  check('malformed defudf', withCode('host', 'declaration-defudf').some((d) => d.message.includes('Unknown type code "q"')), host);
  check('stray call', withCode('host', 'declaration-not-declaration').length === 1, host);
  check('no .clp checks in a declaration file', !has('host', 'Unknown function') && !has('host', 'is a CLIPS built-in'), host);
  check('hand-written duplicate: redundant hint', withCode('extra', 'declaration-redundant').some((d) => d.severity === 4 && d.tags?.includes(1)), JSON.stringify(diagnosticsOf('extra')));

  // 6. Hover, definition, completion.
  const hover = await connection.sendRequest('textDocument/hover', { textDocument: { uri: uri.rules }, position: position(rulesSrc, 'distance 0') });
  const card = hover?.contents?.value ?? '';
  check('hover shows the host function signature', card.includes('(distance <numeric-expression> <numeric-expression> <numeric-expression> <numeric-expression>)'), card);
  check('hover names the dump and its age', card.includes('host function · declared in host.clpd · generated by dump.clp on 2026-10-22 10:00:00'), card);

  const def = await connection.sendRequest('textDocument/definition', { textDocument: { uri: uri.rules }, position: position(rulesSrc, 'distance 0') });
  check('definition of a host function jumps to its defudf line', def?.length === 1 && def[0].uri.toLowerCase().endsWith('host.clpd') && def[0].range.start.line === position(hostSrc, 'distance').line, JSON.stringify(def));

  const sensorHover = await connection.sendRequest('textDocument/hover', { textDocument: { uri: uri.rules }, position: position(rulesSrc, 'sensor') });
  check('a dumped construct says it is declared by the host', (sensorHover?.contents?.value ?? '').includes('declared by the host program in `host.clpd`'), sensorHover?.contents?.value);

  const completion = await connection.sendRequest('textDocument/completion', { textDocument: { uri: uri.comp }, position: position(compSrc + '|', '|') });
  const items = Array.isArray(completion) ? completion : (completion?.items ?? []);
  const distance = items.find((i) => i.label === 'distance');
  check('completion offers the host function', distance?.detail?.endsWith('host function'), JSON.stringify(distance));
  check('completion snippet has its four arguments', (distance?.textEdit?.newText ?? distance?.insertText ?? '').split('${').length - 1 === 4, JSON.stringify(distance?.textEdit));
  check('a dumped built-in is not offered twice', items.filter((i) => i.label === 'abs').length <= 1);

  // 8. Names declared by name only: known, hover, definition, completion.
  const held = JSON.stringify(messages('held'));
  check('name-only template, class and global are known', !has('held', 'Unknown'), held);
  const gripperHover = await connection.sendRequest('textDocument/hover', { textDocument: { uri: uri.held }, position: position(heldSrc, 'gripper') });
  const gripperCard = gripperHover?.contents?.value ?? '';
  check('hover on a name-only template', gripperCard.includes('(defexternal deftemplate gripper)') && gripperCard.includes("slots are unknown, so they aren't checked") && gripperCard.includes('declared in extra.clpd'), gripperCard);
  const globalHover = await connection.sendRequest('textDocument/hover', { textDocument: { uri: uri.held }, position: position(heldSrc, '?*sim-time*') });
  check('hover on a name-only global', (globalHover?.contents?.value ?? '').includes('(defexternal defglobal ?*sim-time*)'), globalHover?.contents?.value);
  const armHover = await connection.sendRequest('textDocument/hover', { textDocument: { uri: uri.held }, position: position(heldSrc, 'Arm') });
  check('hover on a name-only class', (armHover?.contents?.value ?? '').includes('(defexternal defclass Arm)'), armHover?.contents?.value);
  const gripperDef = await connection.sendRequest('textDocument/definition', { textDocument: { uri: uri.held }, position: position(heldSrc, 'gripper') });
  check('definition jumps to the defexternal line', gripperDef?.length === 1 && gripperDef[0].uri.toLowerCase().endsWith('extra.clpd') && gripperDef[0].range.start.line === position(extraSrc, 'gripper').line, JSON.stringify(gripperDef));
  const globalDef = await connection.sendRequest('textDocument/definition', { textDocument: { uri: uri.held }, position: position(heldSrc, '?*sim-time*') });
  check('definition of a name-only global', globalDef?.length === 1 && globalDef[0].range.start.line === position(extraSrc, '?*sim-time*').line, JSON.stringify(globalDef));

  const completionAt = async (key, src) => {
    const result = await connection.sendRequest('textDocument/completion', { textDocument: { uri: uri[key] }, position: position(src + '|', '|') });
    return Array.isArray(result) ? result : (result?.items ?? []);
  };
  const templateItem = (await completionAt('compTemplate', compTemplateSrc)).find((i) => i.label === 'gripper');
  check('completion suggests a name-only template', templateItem?.detail === 'deftemplate (name only) · extra.clpd (host program)', JSON.stringify(templateItem));
  const classItem = (await completionAt('compClass', compClassSrc)).find((i) => i.label === 'Arm');
  check('completion suggests a name-only class', classItem?.detail?.startsWith('defclass (name only)'), JSON.stringify(classItem));
  const resolved = templateItem ? await connection.sendRequest('completionItem/resolve', templateItem) : null;
  const documentation = typeof resolved?.documentation === 'string' ? resolved.documentation : (resolved?.documentation?.value ?? '');
  check('the suggestion is documented with the same card', documentation.includes('(defexternal deftemplate gripper)'), JSON.stringify(resolved?.documentation));
  const dumpedTemplate = (await completionAt('compTemplate', compTemplateSrc)).find((i) => i.label === 'sensor');
  check('a dumped template says it comes from the host program', dumpedTemplate?.detail === 'deftemplate · host.clpd (host program)', JSON.stringify(dumpedTemplate));

  // Hover inside the declaration files themselves.
  const ownLine = await connection.sendRequest('textDocument/hover', { textDocument: { uri: uri.extra }, position: position(extraSrc, 'gripper') });
  check('hover on a defexternal line', (ownLine?.contents?.value ?? '').includes('(defexternal deftemplate gripper)'), ownLine?.contents?.value);
  const ownDef = await connection.sendRequest('textDocument/definition', { textDocument: { uri: uri.extra }, position: position(extraSrc, 'gripper') });
  check('no jump from the defexternal line to itself', ownDef === null || (Array.isArray(ownDef) && ownDef.length === 0), JSON.stringify(ownDef));
  const udfLine = await connection.sendRequest('textDocument/hover', { textDocument: { uri: uri.host }, position: position(hostSrc, 'distance') });
  check('hover on a defudf line', (udfLine?.contents?.value ?? '').includes('host function · declared in host.clpd'), udfLine?.contents?.value);

  // 7. A re-run dump is picked up (the file is closed, as when the host writes it).
  connection.sendNotification('textDocument/didClose', { textDocument: { uri: uri.host } });
  writeFileSync(paths.host, hostSrc.replace('(defudf distance', '(defudf new-fn)\n(defudf distance'));
  connection.sendNotification('workspace/didChangeWatchedFiles', { changes: [{ uri: uri.host, type: 2 }] });
  await sleep(SETTLE_MS);
  check('after the dump changes, the new host function is known', !has('rules', 'Unknown function "new-fn"'), JSON.stringify(messages('rules')));
} finally {
  await connection.sendRequest('shutdown').catch(() => undefined);
  await connection.sendNotification('exit').catch(() => undefined);
  child.kill();
  rmSync(dir, { recursive: true, force: true });
}

if (failures > 0) {
  console.error(`${failures} declaration check(s) failed`);
  process.exit(1);
}
console.log('all declaration checks passed');

/**
 * @file Quick fixes, applied to disk as an editor would. app/ has a
 * generated host.clpd and rules.clp with undefined names and typos; other/
 * has no .clpd file.
 */

import { spawn } from 'node:child_process';
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { createMessageConnection, StreamMessageReader, StreamMessageWriter } from 'vscode-jsonrpc/node.js';

/** The built server. */
const serverPath = fileURLToPath(new URL('../dist/server.js', import.meta.url));

/** A generated dump with one function and one template. */
const hostSrc = `;;; Generated by dump.clp on 2026-10-22 10:00:00 - do not edit by hand, run dump.clp again instead

(defudf distance "*" 4 4 "ld")

(deftemplate MAIN::sensor
   (slot id))
`;

/** Unknown names, slots and typos for the fixes to act on. */
const rulesSrc = `(defrule r1
   (robot (pos ?p) (path $?route))
   (sensr (id ?i))
   (object (is-a Arm) (reach ?r))
   =>
   (assert (robot (pos 1) (path a b c)))
   (printout t ?*sim-time* crlf)
   (plan-path ?p 3)
   (distanse 1 2 3 4))
`;

/** A file in another folder, with no declaration file near it. */
const otherSrc = `(defrule lonely => (no-such-fn))
`;

/** Temporary workspace folder. */
const dir = mkdtempSync(join(tmpdir(), 'clips-fix-'));
mkdirSync(join(dir, 'app'));
mkdirSync(join(dir, 'other'));
/** Fixture paths by key; `externals` is created by a fix. */
const paths = {
  host: join(dir, 'app', 'host.clpd'),
  rules: join(dir, 'app', 'rules.clp'),
  externals: join(dir, 'app', 'externals.clpd'),
  other: join(dir, 'other', 'other.clp')
};
writeFileSync(paths.host, hostSrc);
writeFileSync(paths.rules, rulesSrc);
writeFileSync(paths.other, otherSrc);
/** Fixture URIs by key. */
const uri = Object.fromEntries(Object.entries(paths).map(([key, path]) => [key, pathToFileURL(path).href]));
/**
 * Whether two file URIs name the same file.
 *
 * @param a - A file URI.
 * @param b - Another file URI.
 */
const sameFile = (a, b) => fileURLToPath(a).toLowerCase() === fileURLToPath(b).toLowerCase();

/**
 * Applies LSP text edits to a text.
 *
 * @param text - The text.
 * @param edits - The edits.
 * @returns The new text.
 */
function applyEdits(text, edits) {
  const lines = text.split('\n');
  /** Offset of an LSP position. */
  const offset = (p) => lines.slice(0, p.line).reduce((n, l) => n + l.length + 1, 0) + p.character;
  const sorted = edits.map((e, i) => ({ ...e, i })).sort((a, b) => offset(b.range.start) - offset(a.range.start) || b.i - a.i);
  let out = text;
  for (const e of sorted) out = out.slice(0, offset(e.range.start)) + e.newText + out.slice(offset(e.range.end));
  return out;
}

/**
 * Applies a WorkspaceEdit to the files on disk, as an editor would.
 *
 * @param edit - The edit.
 * @returns The touched paths.
 */
function applyWorkspaceEdit(edit) {
  const touched = [];
  for (const change of edit.documentChanges ?? []) {
    if (change.kind === 'create') {
      const path = fileURLToPath(change.uri);
      if (!existsSync(path)) writeFileSync(path, '');
      continue;
    }
    const path = fileURLToPath(change.textDocument.uri);
    writeFileSync(path, applyEdits(readFileSync(path, 'utf8'), change.edits));
    touched.push(path);
  }
  for (const [u, edits] of Object.entries(edit.changes ?? {})) {
    const path = fileURLToPath(u);
    writeFileSync(path, applyEdits(readFileSync(path, 'utf8'), edits));
    touched.push(path);
  }
  return touched;
}

/**
 * Resolves after `ms` milliseconds.
 *
 * @param ms - The delay.
 * @returns The promise.
 */
const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));
/** Long enough for indexing plus the server's revalidation debounce. */
const SETTLE_MS = 800;

/** The server under test. */
const child = spawn(process.execPath, [serverPath, '--stdio'], { stdio: ['pipe', 'pipe', 'pipe'] });
child.stderr.on('data', (chunk) => process.stderr.write(`[server stderr] ${chunk}`));
/** JSON-RPC connection to the server. */
const connection = createMessageConnection(new StreamMessageReader(child.stdout), new StreamMessageWriter(child.stdin));
/** Latest diagnostics by lowercased path. */
const latest = new Map();
connection.onNotification('textDocument/publishDiagnostics', (p) => latest.set(fileURLToPath(p.uri).toLowerCase(), p.diagnostics));
connection.onRequest('workspace/configuration', (p) => p.items.map(() => ({})));
connection.onRequest('client/registerCapability', () => null);
connection.listen();

/**
 * Latest diagnostics of a fixture.
 *
 * @param key - The fixture key.
 * @returns The diagnostics.
 */
const diagnosticsOf = (key) => latest.get(paths[key].toLowerCase()) ?? [];
/**
 * The unknown-name diagnostic for `name` in a fixture.
 *
 * @param key - The fixture key.
 * @param name - The unknown name.
 * @returns The diagnostic, or `undefined`.
 */
const unknownOf = (key, name) => diagnosticsOf(key).find((d) => d.data?.name === name);
/** Number of failed checks. */
let failures = 0;
/**
 * Records a check result.
 *
 * @param label - What is checked.
 * @param pass - Whether it passed.
 * @param detail - Printed on failure.
 */
function check(label, pass, detail = '') {
  console.log(`${pass ? 'PASS' : 'FAIL'}  ${label}${!pass && detail ? `  (${detail})` : ''}`);
  if (!pass) failures++;
}

/**
 * The code actions for a diagnostic.
 *
 * @param key - The fixture key.
 * @param diagnostic - The diagnostic.
 * @returns The actions.
 */
async function actionsFor(key, diagnostic) {
  return connection.sendRequest('textDocument/codeAction', {
    textDocument: { uri: uri[key] },
    range: diagnostic.range,
    context: { diagnostics: [diagnostic] }
  });
}

/** Version of the last change sent. */
let version = 1;
/**
 * Opens a file with its text on disk.
 *
 * @param key - The fixture key.
 */
function open(key) {
  connection.sendNotification('textDocument/didOpen', { textDocument: { uri: uri[key], languageId: 'clips', version: 1, text: readFileSync(paths[key], 'utf8') } });
}
/**
 * Sends a file's new text on disk as a change.
 *
 * @param key - The fixture key.
 */
function changed(key) {
  connection.sendNotification('textDocument/didChange', {
    textDocument: { uri: uri[key], version: ++version },
    contentChanges: [{ text: readFileSync(paths[key], 'utf8') }]
  });
}
/**
 * Reports a file change on disk.
 *
 * @param key - The fixture key.
 * @param type - 1 created, 2 changed, 3 deleted.
 */
function changedOnDisk(key, type = 2) {
  connection.sendNotification('workspace/didChangeWatchedFiles', { changes: [{ uri: uri[key], type }] });
}

try {
  const folderUri = pathToFileURL(dir).href;
  await connection.sendRequest('initialize', {
    processId: process.pid,
    rootUri: folderUri,
    workspaceFolders: [{ uri: folderUri, name: 'ws' }],
    capabilities: { workspace: { workspaceFolders: true, configuration: true, workspaceEdit: { documentChanges: true, resourceOperations: ['create'] } } }
  });
  await connection.sendNotification('initialized', {});
  await sleep(SETTLE_MS);
  open('rules');
  open('other');
  await sleep(SETTLE_MS);

  // 1. The menu.
  const robot = unknownOf('rules', 'robot');
  const robotActions = (await actionsFor('rules', robot)) ?? [];
  const titles = robotActions.map((a) => a.title);
  const withSlots = robotActions.find((a) => a.title.startsWith('Declare template "robot" as external (slots pos, path)'));
  const created = withSlots?.edit?.documentChanges?.find((c) => c.kind === 'create');
  const insertedText = withSlots?.edit?.documentChanges?.find((c) => c.textDocument)?.edits?.[0]?.newText ?? '';
  check('declare with the slots the workspace uses', !!withSlots, JSON.stringify(titles));
  check('it creates externals.clpd beside the dump', created && sameFile(created.uri, uri.externals), JSON.stringify(created));
  check('a slot used with $? or several values is a multislot', insertedText.includes('(deftemplate robot\n   (slot pos)\n   (multislot path))'), insertedText);
  check('name-only declaration offered', titles.some((t) => t.includes('(name only, slots unchecked)')), JSON.stringify(titles));
  check('define in this file offered', robotActions.some((a) => a.title === 'Define template "robot" in this file' && a.edit.changes[uri.rules]?.[0]?.newText.startsWith('(deftemplate robot')), JSON.stringify(titles));
  check('no did-you-mean without a close name', !titles.some((t) => t.startsWith('Change to')), JSON.stringify(titles));

  const typo = unknownOf('rules', 'sensr');
  const typoActions = (await actionsFor('rules', typo)) ?? [];
  check('a typo gets "Change to" first, preferred', typoActions[0]?.title === 'Change to "sensor"' && typoActions[0].isPreferred === true, JSON.stringify(typoActions.map((a) => a.title)));
  const fnTypo = (await actionsFor('rules', unknownOf('rules', 'distanse'))) ?? [];
  check('a host-function typo gets "Change to"', fnTypo[0]?.title === 'Change to "distance"', JSON.stringify(fnTypo.map((a) => a.title)));

  const arm = (await actionsFor('rules', unknownOf('rules', 'Arm'))) ?? [];
  const armText = arm.find((a) => a.title.startsWith('Declare class "Arm" as external (slot reach)'))?.edit?.documentChanges?.[1]?.edits?.[0]?.newText ?? '';
  check('class declared with the slots its object patterns use', armText.includes('(defclass Arm\n   (is-a USER)\n   (slot reach))'), JSON.stringify(arm.map((a) => a.title)));

  // 2. The bulk fix.
  const bulk = robotActions.find((a) => a.title.startsWith('Declare all'));
  check('bulk fix leaves out the likely typos', bulk?.title === 'Declare all 4 unknown names in this file as external in externals.clpd (2 likely typos left out: sensr, distanse)', bulk?.title);
  applyWorkspaceEdit(bulk.edit);
  const externals = readFileSync(paths.externals, 'utf8');
  const order = ['(deftemplate robot', '(defclass Arm', '(defexternal defglobal ?*sim-time*)', '(defudf plan-path)'].map((t) => externals.indexOf(t));
  check('entries are written grouped by kind', order.every((i, n) => i >= 0 && (n === 0 || i > order[n - 1])), externals);
  check('the new file explains itself', externals.startsWith('; Hand-written declarations for the CLIPS language server'));
  changedOnDisk('externals', 1);
  await sleep(SETTLE_MS);
  const remaining = diagnosticsOf('rules').filter((d) => d.data?.name).map((d) => d.data.name);
  check('declared names are known now', ['robot', 'Arm', '?*sim-time*', 'plan-path'].every((n) => !remaining.includes(n)), JSON.stringify(remaining));
  check('the typos are still flagged', remaining.includes('sensr') && remaining.includes('distanse'), JSON.stringify(remaining));

  // 6. Messages (with a dump that lacks the name; with no declaration file).
  check('message names the dump and its age', unknownOf('rules', 'sensr')?.message.includes('Not in host.clpd (generated 2026-10-22 10:00:00) either'), unknownOf('rules', 'sensr')?.message);
  check('without any declaration file, the message says how to get one', unknownOf('other', 'no-such-fn')?.message.includes('run scripts/dump-host/dump.clp'), unknownOf('other', 'no-such-fn')?.message);

  // 3. A later fix inserts into the existing file, in order.
  writeFileSync(paths.rules, rulesSrc + '\n(defrule r2 (gripper (open TRUE)) (robot (speed 3)) (sensor (idd 1)) =>)\n');
  changed('rules');
  await sleep(SETTLE_MS);
  const gripper = (await actionsFor('rules', unknownOf('rules', 'gripper'))) ?? [];
  const gripperEdit = gripper.find((a) => a.title.startsWith('Declare template "gripper" as external (slot open)'))?.edit;
  const robotLine = externals.split('\n').findIndex((l) => l.startsWith('(deftemplate robot'));
  check('an existing file is edited, not created', gripperEdit && !gripperEdit.documentChanges.some((c) => c.kind === 'create'), JSON.stringify(gripperEdit));
  check('inserted at its sorted place (before robot)', gripperEdit?.documentChanges?.[0]?.edits?.[0]?.range.start.line === robotLine, JSON.stringify(gripperEdit?.documentChanges?.[0]?.edits));

  // 4. Add slot.
  const speed = diagnosticsOf('rules').find((d) => d.code === 'clips(slot-unknown)' && d.data?.slot === 'speed');
  const speedFix = ((await actionsFor('rules', speed)) ?? []).find((a) => a.title.startsWith('Add slot "speed"'));
  check('add slot to a template from the hand-written file', !!speedFix, JSON.stringify(speed));
  if (speedFix) {
    applyWorkspaceEdit(speedFix.edit);
    check('the slot is added inside the template', readFileSync(paths.externals, 'utf8').includes('   (multislot path)\n   (slot speed))'), readFileSync(paths.externals, 'utf8'));
  }
  const idd = diagnosticsOf('rules').find((d) => d.code === 'clips(slot-unknown)' && d.data?.slot === 'idd');
  const iddFixes = ((await actionsFor('rules', idd)) ?? []).filter((a) => a.title.startsWith('Add slot'));
  check('no add-slot into the generated dump', idd && iddFixes.length === 0, JSON.stringify(idd));

  // 5. Remove an unused declaration.
  writeFileSync(paths.externals, readFileSync(paths.externals, 'utf8') + '(defexternal deftemplate nobody)\n');
  open('externals');
  await sleep(SETTLE_MS);
  const unused = diagnosticsOf('externals').find((d) => d.code === 'clips(declaration-unused)');
  check('unused declaration hinted', unused?.message.startsWith('Deftemplate "nobody" is declared but no .clp file'), JSON.stringify(diagnosticsOf('externals')));
  const removeFix = ((await actionsFor('externals', unused)) ?? []).find((a) => a.title === 'Remove this declaration');
  if (removeFix) applyWorkspaceEdit(removeFix.edit);
  check('remove deletes its line', removeFix && !readFileSync(paths.externals, 'utf8').includes('nobody'), JSON.stringify(removeFix));
} finally {
  await connection.sendRequest('shutdown').catch(() => undefined);
  await connection.sendNotification('exit').catch(() => undefined);
  child.kill();
  rmSync(dir, { recursive: true, force: true });
}

if (failures > 0) {
  console.error(`${failures} quick-fix check(s) failed`);
  process.exit(1);
}
console.log('all quick-fix checks passed');
